import os
import gradio as gr

from fastapi import FastAPI

# =========================================
# LangChain
# =========================================
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage

# =========================================
# ChatOpenAI 생성
# =========================================
# streaming=True
# → stream() 메서드 사용 가능
# → 토큰 생성 시 즉시 전달
# =========================================

llm = ChatOpenAI(
    model="gpt-4.1-mini",
    api_key=os.getenv("OPENAI_API_KEY"),
    temperature=0.7,
    streaming=True  # 응답을 스크림(비동기)으로 받을 수 있게 설정
)

# =========================================
# 채팅 함수
# =========================================
# message : 현재 사용자 입력
# history : 이전 대화 이력
#
# ChatInterface에서 호출됨
# =========================================

def chat(message, history):

    # -------------------------------------
    # LangChain 메시지 생성
    # -------------------------------------
    # 현재는 단일 질문만 GPT에 전달
    # (대화 이력은 사용하지 않습니다. 이전 질문이 무엇인지 알 수 없습니다)
    # -------------------------------------

    messages = [
        HumanMessage(content=message)
    ]

    # -------------------------------------
    # 누적 응답 저장 변수
    # -------------------------------------

    partial_message = ""

    # -------------------------------------
    # GPT 스트리밍 호출
    # -------------------------------------
    # chunk 단위로 응답 수신
    # -------------------------------------

    for chunk in llm.stream(messages):

        # 빈 토큰 제외
        if chunk.content:

            # 응답 누적
            partial_message += chunk.content

            # ---------------------------------
            # yield
            # ---------------------------------
            # Gradio가 이 값을 받을 때마다
            # 화면을 갱신
            # ---------------------------------

            yield partial_message


# =========================================
# Gradio Chat UI 생성
# =========================================

demo = gr.ChatInterface(
    fn=chat,
    title="LangChain ChatBot"
)

# =========================================
# FastAPI 생성
# =========================================

app = FastAPI()

# =========================================
# FastAPI에 Gradio 연결
# =========================================

app = gr.mount_gradio_app(
    app,
    demo,
    path="/"
)

