# PDF 파일에서 표(Table)를 추출하기 위한 라이브러리
import pdfplumber

# 표 데이터를 DataFrame 형태로 다루기 위한 라이브러리
import pandas as pd


# 분석할 PDF 파일 경로
pdf_path = "data/과정기반 작물모형을 이용한 웹 기반 밀 재배관리 의사결정 지원시스템 설계 및 구축.pdf"

# 추출된 모든 표(DataFrame)를 저장할 리스트
all_tables = []


# PDF 파일 열기
# with 구문을 사용하면 작업 종료 후 자동으로 파일이 닫힘
with pdfplumber.open(pdf_path) as pdf:

    # PDF 페이지는 0부터 시작
    # 따라서 PDF 문서의 6페이지는 index=5
    page = pdf.pages[5]

    # 현재 페이지의 크기 출력
    print(f"페이지 크기 : {page.width} x {page.height}")

    # ----------------------------------------------------
    # 표 추출
    # ----------------------------------------------------
    # extract_tables()
    # 현재 페이지에서 인식된 모든 표를 리스트 형태로 반환
    #
    # 반환 예시
    # [
    #     [
    #         ["이름","나이","직업"],
    #         ["홍길동","30","개발자"],
    #         ["김철수","25","학생"]
    #     ],
    #     ...
    # ]
    # ----------------------------------------------------
    tables = page.extract_tables()

    # 발견된 표 개수 출력
    print(f"\n발견된 표 개수 : {len(tables)}")

    # ----------------------------------------------------
    # 추출된 표들을 하나씩 처리
    # ----------------------------------------------------
    for idx, table in enumerate(tables):

        print(f"\n{'='*60}")
        print(f"TABLE {idx+1}")
        print(f"{'='*60}")

        # ------------------------------------------------
        # 리스트 형태의 표를 DataFrame으로 변환
        # ------------------------------------------------
        df = pd.DataFrame(table)

        # 현재 상태 예시
        #
        #        0      1      2
        # 0    이름    나이   직업
        # 1  홍길동    30   개발자
        # 2  김철수    25    학생

        # ------------------------------------------------
        # 첫 번째 행을 컬럼명(Header)으로 지정
        # ------------------------------------------------
        df.columns = df.iloc[0]

        # 첫 번째 행은 이미 컬럼명으로 사용했으므로 제거
        df = df[1:].reset_index(drop=True)

        # 결과 예시
        #
        #     이름    나이   직업
        # 0 홍길동   30   개발자
        # 1 김철수   25    학생

        # 추출된 표를 리스트에 저장
        all_tables.append(df)

        # 표 내용 출력
        print(df)

        # ------------------------------------------------
        # CSV 파일로 저장
        # ------------------------------------------------
        csv_file = f"table_{idx+1}.csv"

        # utf-8-sig
        # 엑셀에서 한글 깨짐 방지를 위해 사용
        df.to_csv(
            csv_file,
            index=False,        # 인덱스 저장 안함
            encoding="utf-8-sig"
        )

        print(f"\n저장 완료 : {csv_file}")


# --------------------------------------------------------
# 전체 표 개수 확인
# --------------------------------------------------------
print(f"\n총 저장된 표 개수 : {len(all_tables)}")

