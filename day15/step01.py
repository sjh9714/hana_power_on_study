# =============================================================================
# Chroma Vector DB
# =============================================================================
from langchain_chroma import Chroma

# =============================================================================
# HuggingFace Embedding
# =============================================================================
from langchain_huggingface import HuggingFaceEmbeddings

# =============================================================================
# OpenAI Chat Model
# =============================================================================
from langchain_openai import ChatOpenAI

# =============================================================================
# Prompt Template
# =============================================================================
from langchain_core.prompts import PromptTemplate

# =============================================================================
# Output Parser
# =============================================================================
from langchain_core.output_parsers import StrOutputParser

# =============================================================================
# LCEL Runnable
# =============================================================================
from langchain_core.runnables import (
    RunnablePassthrough,
    RunnableLambda
)

import os

##############################################################################
# 환경 설정
##############################################################################

# Chroma Collection 이름
COLLECTION_NAME = "pdf_collection"

# Chroma DB 저장 경로
PERSIST_DIRECTORY = "./chroma_db"

# 사용할 임베딩 모델
EMBEDDING_MODEL = (
    "sentence-transformers/all-MiniLM-L6-v2"
)

##############################################################################
# Embedding Model
##############################################################################

def get_embedding_model():
    """
    텍스트를 벡터(Vector)로 변환하는 모델

    예)

    "사과 재배"

        ↓

    [0.123, -0.451, 0.992, ...]
    """

    return HuggingFaceEmbeddings(
        model_name=EMBEDDING_MODEL
    )

##############################################################################
# Vector Store
##############################################################################

def load_vector_store():
    """
    Chroma DB 연결
    """

    embedding_model = get_embedding_model()

    return Chroma(
        collection_name=COLLECTION_NAME,
        persist_directory=PERSIST_DIRECTORY,
        embedding_function=embedding_model
    )

##############################################################################
# Vector Store 로드
##############################################################################

vector_store = load_vector_store()

##############################################################################
# Retriever 생성
##############################################################################

"""
Retriever 역할

사용자 질문(Query)과
가장 유사한 문서를 검색

상위 3개 문서 반환
"""

retriever = vector_store.as_retriever(
    search_kwargs={
        "k": 3
    }
)

##############################################################################
# RunnableLambda
##############################################################################

def format_docs_with_pages(docs):
    """
    Retriever가 반환한 Document 리스트를

    1. Context 문자열 생성
    2. Page 번호 추출
    3. Context 마지막에 Page 정보 추가

    반환 예

    문서 내용1

    문서 내용2

    문서 내용3

    참고 페이지:
    3, 5, 8
    """

    ##################################################
    # 문서 내용 합치기
    ##################################################

    context = "\n\n".join(
        doc.page_content
        for doc in docs
    )

    ##################################################
    # 페이지 번호 추출
    ##################################################

    pages = sorted(
        set(
            doc.metadata.get("page")
            for doc in docs
            if doc.metadata.get("page") is not None
        )
    )

    ##################################################
    # 페이지 번호 문자열 생성
    ##################################################

    page_text = ", ".join(
        str(page + 1)
        for page in pages
    )

    ##################################################
    # Context + Page 정보 반환
    ##################################################

    return f"""
{context}

참고 페이지:
{page_text}
"""

##############################################################################
# RunnableLambda 생성
##############################################################################

format_docs = RunnableLambda(
    format_docs_with_pages
)

##############################################################################
# Prompt Template
##############################################################################

prompt = PromptTemplate.from_template(
"""
당신은 스마트농업 전문가입니다.

반드시 제공된 문서 내용만 사용하여 답변하세요.

문서:
{context}

질문:
{query}

답변 작성 규칙:

1. 문서 내용만 사용한다.
2. 문서에 없는 내용은 추측하지 않는다.
3. 핵심 내용을 요약한다.
4. 문서에 없는 경우
   "문서에서 찾을 수 없습니다."
   라고 답변한다.
5. 참고 페이지를 함께 표시한다.

답변:
"""
)

##############################################################################
# LLM
##############################################################################

llm = ChatOpenAI(
    model="gpt-4.1-mini",
    api_key=os.getenv("OPENAI_API_KEY"),
    temperature=0
)

##############################################################################
# Output Parser
##############################################################################

"""
AIMessage

↓

문자열(String)
"""

parser = StrOutputParser()

##############################################################################
# LCEL Chain
##############################################################################

"""
동작 순서

      사용자 질문
            │
            ▼
 ┌───────────────────────┐
 │ RunnableParallel      │
 └───────────────────────┘
      │
      ├──────────────────────────┐
      │                          │
      ▼                          ▼
retriever                 RunnablePassthrough
      │                          │
      ▼                          ▼
format_docs              질문 그대로 유지
      │
      ▼
context 생성
      │
      └──────────────┬──────────────┘
                     ▼
{
   "context": 검색문서,
   "query": 사용자질문
}
                     │
                     ▼
               PromptTemplate
                     │
                     ▼
                 ChatOpenAI
                     │
                     ▼
              StrOutputParser
                     │
                     ▼

                 최종 답변
"""

chain = (
    {
        # 병렬 실행
        "context": retriever | format_docs,
        "query": RunnablePassthrough()
    }
    # 순차 실행
    | prompt
    | llm
    | parser
)

##############################################################################
# 실행
##############################################################################

# query = "농작물 재배관리 의사결정에 대해 알려줘"

# answer = chain.invoke(query)

# print(answer)

queries = [

    "작물모형을 이용한 웹 기반 밀 재배관리 의사결정 지원시스템",
    "밀 재배관리 방법 알려줘",
    "토양 관리 방법 알려줘",

    "GPT란 무엇인가?",
    "LangChain LCEL이란?",
    "Docker란 무엇인가?"

]

for query in queries:

    answer = chain.invoke(query)

    print()
    print(answer)
    print()
    print("=" * 60)
